// The stored file, once the loop has checked it
static struct {
    bool checked = false, valid = false;
    uint32_t size = 0, crc = 0;
    char version[13] = "";
    File f;
} gFile;

static bool useFile() { return gFile.checked && gFile.valid; }

uint32_t advControllerImageSize() {
    if (useFile()) return gFile.size;
#if HAVE_EMBEDDED
    return ADV_CONTROLLER_IMAGE_SIZE;
#else
    return 0;
#endif
}
uint32_t advControllerImageCrc() {
    if (useFile()) return gFile.crc;
#if HAVE_EMBEDDED
    return ADV_CONTROLLER_IMAGE_CRC;
#else
    return 0;
#endif
}
const char* advControllerImageVersion() {
    if (useFile()) return gFile.version;
#if HAVE_EMBEDDED
    return ADV_CONTROLLER_IMAGE_VERSION;
#else
    return "";
#endif
}
const char* advControllerImageSource() { return useFile() ? "file" : HAVE_EMBEDDED ? "embedded" : "none"; }

void advControllerImageRead(uint32_t offset, uint8_t* out, uint8_t n) {
    const uint32_t size = advControllerImageSize();
    if (offset >= size) return;
    if (offset + n > size) n = (uint8_t)(size - offset);
    if (useFile()) {
        if (!gFile.f) gFile.f = LittleFS.open(ADV_IMAGE_PATH, "r");
        if (!gFile.f || !gFile.f.seek(offset) || gFile.f.read(out, n) != n) memset(out, 0xFF, n);   // the CRC check fails
        return;
    }
#if HAVE_EMBEDDED
    memcpy_P(out, kAdvControllerImage + offset, n);
#endif
}

void advControllerImageClose() { if (gFile.f) gFile.f.close(); }

// The whole stored file: header, length and CRC (once at boot, ~50 KB read)
static void checkStored() {
    gFile.checked = true;
    gFile.valid = false;
    File f = LittleFS.open(ADV_IMAGE_PATH, "r");
    if (!f) return;
    AdvImageCheck c;
    uint8_t buf[256];
    size_t n;
    while ((n = f.read(buf, sizeof(buf))) > 0) {
        c.add(buf, n);
        if (c.received > ADV_IMAGE_MAX_BYTES) break;
        yield();
    }
    f.close();
    AdvImageHeader h;
    const char* err = c.done(h);
    if (err) {
        LittleFS.remove(ADV_IMAGE_PATH);
        logPrintf(LC_UPDATE, LL_INFO, PSTR("ADV Controller image file: %s, removed"), err);
        return;
    }
    gFile.valid = true;
    gFile.size = h.length;
    gFile.crc = h.crc;
    memcpy(gFile.version, h.version, sizeof(gFile.version));
    logPrintf(LC_UPDATE, LL_INFO, PSTR("ADV Controller image file: %s build %08lX (%u KB)"), gFile.version,
              (unsigned long)gFile.crc, (unsigned)(gFile.size / 1024));
}

// ---- upload --------------------------------------------------------------------------------------------------

static struct {
    bool active = false;          // chunks arriving
    bool swapPending = false;     // finished and valid: the loop moves the temp file in
    const char* err = nullptr;    // the first failure ("forbidden", "busy", "space", "write", "format", "size", "crc")
    bool paused = false;
    File f;
    AdvImageCheck chk;
    AdvImageHeader hdr;
    AsyncWebServerRequest* owner = nullptr;
    UploadWatchdog wd;
} gUp;

bool advImageUploadActive() { return gUp.active || gUp.swapPending; }

static void upDrop() {            // network context or loop: the temp file goes, saving resumes
    gUp.wd.stop();
    if (gUp.f) gUp.f.close();
    LittleFS.remove(ADV_IMAGE_TMP_PATH);
    if (gUp.paused) { settingsSaverPause(SAVER_HOLD_ADV_IMAGE, false); gUp.paused = false; }
}

void advImageUploadChunk(AsyncWebServerRequest* req, size_t index, const uint8_t* data, size_t len, bool final) {
    if (index == 0) {
        if (gUp.active || gUp.swapPending) return;                 // a second upload: its finish answers 409
        gUp = {};
        gUp.owner = req;
        gUp.active = true;
        gUp.wd.touch(millis());                                   // also a refused one: a vanished client frees it
        if (!apiGuardRequest(req)) { gUp.err = "forbidden"; return; }   // uploads run before the middleware
        if (!platformLinkHardware()) { gUp.err = "no_adv"; return; }     // a standard board has no ADV Controller
        if (advLinkUpdateActive() || updateInProgress()) { gUp.err = "busy"; return; }
        if (req->contentLength() > ADV_IMAGE_MAX_BYTES + 4096) { gUp.err = "size"; return; }   // + the multipart envelope
        FSInfo fi;
        if (!LittleFS.info(fi) || req->contentLength() + 16384 > fi.totalBytes - fi.usedBytes) { gUp.err = "space"; return; }
        settingsSaverPause(SAVER_HOLD_ADV_IMAGE, true);
        gUp.paused = true;
        gUp.f = LittleFS.open(ADV_IMAGE_TMP_PATH, "w");            // the one LittleFS write in this handler
        if (!gUp.f) { gUp.err = "write"; upDrop(); return; }
    }
    if (req != gUp.owner || gUp.err) return;
    gUp.wd.touch(millis());
    if (gUp.chk.received + len > ADV_IMAGE_MAX_BYTES) { gUp.err = "size"; upDrop(); return; }
    if (gUp.f.write(data, len) != len) { gUp.err = "space"; upDrop(); return; }
    gUp.chk.add(data, len);
    if (final) gUp.f.close();
}

int advImageUploadFinish(AsyncWebServerRequest* req, char* json, size_t n) {
    if (!gUp.owner || req != gUp.owner) {                           // no body, or refused because another one runs
        const bool busy = gUp.active || gUp.swapPending;
        snprintf_P(json, n, busy ? PSTR("{\"error\":\"busy\"}") : PSTR("{\"error\":\"format\"}"));
        return busy ? 409 : 400;
    }
    gUp.owner = nullptr;
    gUp.active = false;
    gUp.wd.stop();
    const char* err = gUp.err;
    if (!err) {
        if (gUp.f) gUp.f.close();
        err = gUp.chk.done(gUp.hdr);
        if (err) upDrop();
    } else {
        upDrop();
    }
    if (err) {
        logPrintf(LC_UPDATE, LL_INFO, PSTR("ADV Controller image upload refused: %s"), err);
        snprintf_P(json, n, PSTR("{\"error\":\"%s\"}"), err);
        return strcmp(err, "forbidden") == 0 ? 403 : strcmp(err, "busy") == 0 ? 409 : strcmp(err, "space") == 0 ? 413 : 400;
    }
    gUp.swapPending = true;                                          // the loop renames it (no second write here)
    snprintf_P(json, n, PSTR("{\"ok\":1,\"version\":\"%s\",\"build\":\"%08lX\"}"), gUp.hdr.version, (unsigned long)gUp.hdr.crc);
    return 200;
}

void advControllerImageLoop(bool controllerOk, uint32_t runningBuild, bool updating) {
    if (!gFile.checked) checkStored();
    if (gUp.active && gUp.wd.expired(millis())) {                   // the client went away mid-upload
        gUp.active = false;
        gUp.owner = nullptr;
        upDrop();
        logPrintf(LC_UPDATE, LL_INFO, PSTR("ADV Controller image upload abandoned (no data for 30 s)"));
    }
    if (gUp.swapPending && !updating) {
        advControllerImageClose();
        LittleFS.remove(ADV_IMAGE_PATH);
        const bool ok = LittleFS.rename(ADV_IMAGE_TMP_PATH, ADV_IMAGE_PATH);
        gUp.swapPending = false;
        if (gUp.paused) { settingsSaverPause(SAVER_HOLD_ADV_IMAGE, false); gUp.paused = false; }
        if (ok) {
            gFile.checked = gFile.valid = true;
            gFile.size = gUp.hdr.length;
            gFile.crc = gUp.hdr.crc;
            memcpy(gFile.version, gUp.hdr.version, sizeof(gFile.version));
            logPrintf(LC_UPDATE, LL_INFO, PSTR("ADV Controller image uploaded: %s build %08lX (%u KB)"), gFile.version,
                      (unsigned long)gFile.crc, (unsigned)(gFile.size / 1024));
        } else {
            gFile.valid = false;
            LittleFS.remove(ADV_IMAGE_TMP_PATH);
            logPrintf(LC_UPDATE, LL_INFO, PSTR("ADV Controller image upload: rename failed"));
        }
    }
    // Installed: the file has done its job
    if (useFile() && controllerOk && !updating && !gUp.swapPending && runningBuild == gFile.crc) {
        advControllerImageClose();
        LittleFS.remove(ADV_IMAGE_PATH);
        gFile.valid = false;
        logPrintf(LC_UPDATE, LL_INFO, PSTR("ADV Controller runs build %08lX: image file removed"), (unsigned long)runningBuild);
    }
}
