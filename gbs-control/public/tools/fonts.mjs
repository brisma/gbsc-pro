// Writes app/art/logo.tsx: the wordmark outlined from Archivo (@fontsource/archivo, a dev dependency) so the page
// embeds no font file for it. Run after changing the logo: node tools/fonts.mjs
import { writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { python } from "./python.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const req = createRequire(import.meta.url);
const f900 = req.resolve("@fontsource/archivo/files/archivo-latin-900-normal.woff2");
const f800 = req.resolve("@fontsource/archivo/files/archivo-latin-800-normal.woff2");
const r = spawnSync(python(), ["-I", join(root, "tools", "logo-outline.py"), f900, f800], { encoding: "utf8" });
if (r.status !== 0) { process.stderr.write(r.stderr ?? ""); process.exit(1); }
const p = JSON.parse(r.stdout);
const out = `// Generated by tools/fonts.mjs from Archivo (SIL Open Font License) — do not edit; run node tools/fonts.mjs
// The wordmark: GBS in white, the C on an accent tile, PRO in the accent (yellow)
const GBS = "${p.gbs}";
const C = "${p.c}";
const PRO = "${p.pro}";

export function Logo({ height = 28 }: { height?: number }) {
  return (
    <svg class="logo" viewBox="-3 0 235 44" height={height} width={Math.round((height * 235) / 44)} role="img" aria-label="GBSC PRO">
      <path d={GBS} fill="var(--t1)" />
      <rect x="87.5" y="2" width="37" height="40" rx="8" fill="var(--ac)" />
      <path d={C} fill="var(--acx)" />
      <path d={PRO} fill="var(--ac)" />
    </svg>
  );
}
`;
writeFileSync(join(root, "app", "art", "logo.tsx"), out);
console.log(`fonts: app/art/logo.tsx ${out.length} B`);
