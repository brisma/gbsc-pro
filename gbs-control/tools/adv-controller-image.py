#!/usr/bin/env python3
"""Embeds the ADV Controller firmware image in the ESP build (link v3).

PlatformIO pre-script (extra_scripts = pre:tools/adv-controller-image.py): turns ../adv-controller/release/adv-controller.bin
into pro/link/adv-controller-image.gen.h (PROGMEM array + size, CRC32 build id, version), regenerated only when the image
changes. The image header (app offset 0x400, see adv-controller/tools/fw-header.py) is verified first.

Standalone: adv-controller-image.py --self-test
"""
import os
import re
import struct
import sys
import tempfile
import zlib

HDR_OFF = 0x400
HDR_FMT = "<4sHH12sII"


def parse_image(data):
    if len(data) < HDR_OFF + struct.calcsize(HDR_FMT):
        raise ValueError("image too short")
    magic, _hv, _res, ver, length, crc = struct.unpack_from(HDR_FMT, data, HDR_OFF)
    if magic != b"ADVC":
        raise ValueError("no ADV Controller header (ADVC) at 0x400")
    if length != len(data):
        raise ValueError("header length %d != file size %d" % (length, len(data)))
    body = bytearray(data)
    struct.pack_into("<I", body, HDR_OFF + 24, 0)
    if zlib.crc32(bytes(body)) & 0xFFFFFFFF != crc:
        raise ValueError("header CRC32 does not match the image")
    return ver.split(b"\x00")[0].decode(), crc


def render(data, version, crc):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
    return ("// Generated by tools/adv-controller-image.py from adv-controller/release/adv-controller.bin: do not edit\n"
            "#pragma once\n"
            "#define ADV_CONTROLLER_IMAGE_CRC 0x%08Xu\n"
            "#define ADV_CONTROLLER_IMAGE_SIZE %du\n"
            "#define ADV_CONTROLLER_IMAGE_VERSION \"%s\"\n"
            "static const uint8_t kAdvControllerImage[] PROGMEM = {\n%s\n};\n") % (crc, len(data), version, "\n".join(rows))


def generate(bin_path, out_path):
    if not os.path.exists(bin_path):
        raise SystemExit("adv-controller-image: %s is missing (run `make release` in adv-controller/)" % bin_path)
    data = open(bin_path, "rb").read()
    try:
        version, crc = parse_image(data)
    except ValueError as e:
        raise SystemExit("adv-controller-image: %s: %s" % (bin_path, e))
    if os.path.exists(out_path):
        m = re.search(r"ADV_CONTROLLER_IMAGE_CRC 0x([0-9A-F]{8})u", open(out_path).read())
        if m and int(m.group(1), 16) == crc:
            return False
    open(out_path, "w").write(render(data, version, crc))
    print("adv-controller-image: embedded ADV Controller %s (%d bytes, build %08X)" % (version, len(data), crc))
    return True


def self_test():
    img = bytearray(os.urandom(4096))
    struct.pack_into(HDR_FMT, img, HDR_OFF, b"ADVC", 1, 0, b"9.8.7", len(img), 0)
    body = bytearray(img)
    struct.pack_into("<I", body, HDR_OFF + 24, 0)
    struct.pack_into("<I", img, HDR_OFF + 24, zlib.crc32(bytes(body)) & 0xFFFFFFFF)
    with tempfile.TemporaryDirectory() as d:
        b, h = os.path.join(d, "a.bin"), os.path.join(d, "a.h")
        open(b, "wb").write(img)
        assert generate(b, h)
        assert not generate(b, h), "regenerated an unchanged image"
        text = open(h).read()
        got = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-F]{2}),", text))
        assert got == bytes(img), "bytes differ"
        assert '"9.8.7"' in text and ("%du" % len(img)) in text
        img[10] ^= 1
        open(b, "wb").write(img)
        try:
            generate(b, h)
            raise AssertionError("a corrupted image was accepted")
        except SystemExit:
            pass
    print("adv-controller-image self-test: ok")


if __name__ == "__main__" and "--self-test" in sys.argv:
    self_test()
else:
    try:
        Import("env")   # noqa: F821 (SCons)
        _proj = env["PROJECT_DIR"]   # noqa: F821
        # tools/dev.py build (both controllers) embeds the ADV image it just built, so the pair it flashes agrees;
        # releases and plain pio builds embed the committed release image
        _image = os.environ.get("GBSC_ADV_IMAGE") or os.path.join(_proj, "..", "adv-controller", "release", "adv-controller.bin")
        generate(_image, os.path.join(_proj, "pro", "link", "adv-controller-image.gen.h"))
    except NameError:
        if __name__ == "__main__":
            sys.exit(__doc__)
