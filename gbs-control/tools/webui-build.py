#!/usr/bin/env python3
"""Builds the web app and the register map before the ESP8266 firmware when their headers are missing or stale.

PlatformIO pre-script (extra_scripts = pre:tools/webui-build.py, env gbsc-pro). The firmware serves the new web app
(public/app): `npm run gen` when the firmware tables changed (public/gen, native exporter), `npm run build:app`
(dist/app.html), then webui_html.h = the page gzipped, with the symbols gbs-control.ino uses. Generated files are not
in git: a fresh clone builds them here, which needs Node.js 22.18+ (26 recommended) and npm, PlatformIO with a host C++
compiler (gen) and Python with fonttools/brotli (icon subset). tools/dev.py doctor checks every prerequisite.
"""
import glob
import gzip
import os
import shutil
import subprocess
import sys

SOURCE_GLOBS = ("public/app/**/*", "public/tools/build-app.mjs", "public/tools/icons-app.mjs", "public/tools/icons-subset.py",
                "public/tools/fonts.mjs", "public/tools/size.mjs", "public/gen/*.json", "public/package.json")


def python_cmd():
    """PYTHON when set (tools/dev.py), else python on Windows (python3 there can be the Store stub), python3 elsewhere."""
    return os.environ.get("PYTHON") or shutil.which("python" if os.name == "nt" else "python3")


def needs_build(root):
    """True when webui_html.h is missing or older than any source of the web app."""
    header = os.path.join(root, "webui_html.h")
    if not os.path.exists(header):
        return True
    built = os.path.getmtime(header)
    for pattern in SOURCE_GLOBS:
        for path in glob.glob(os.path.join(root, pattern), recursive=True):
            if os.path.isfile(path) and os.path.getmtime(path) > built:
                return True
    return False


def write_header(page, header):
    """webui_html.h: the page gzipped (-9, no timestamp) as const uint8_t webui_html[] PROGMEM + webui_html_len."""
    with open(page, "rb") as f:
        gz = gzip.compress(f.read(), 9, mtime=0)
    lines = ["// Generated by tools/webui-build.py from public/dist/app.html (the web app). Not in git.",
             "#pragma once", "#include <Arduino.h>", "const uint8_t webui_html[] PROGMEM = {"]
    for i in range(0, len(gz), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
    lines.append("};")
    lines.append("const unsigned int webui_html_len = %d;" % len(gz))
    with open(header, "w") as f:
        f.write("\n".join(lines) + "\n")
    return len(gz)


def build(root):
    if not needs_build(root):
        print("webui: up to date")
        return
    missing = [t for t in ("node", "npm") if not shutil.which(t)]
    if missing:
        sys.exit("webui: Node.js 22.18+ and npm are needed to build the web app (https://nodejs.org); missing: %s" % ", ".join(missing))
    npm = shutil.which("npm")   # npm.cmd on Windows: a bare "npm" is not found without a shell
    print("webui: building the web app")
    web = os.path.join(root, "public")
    stamp = os.path.join(web, "node_modules", ".package-lock.json")   # a container mount point exists empty
    if not os.path.isfile(stamp) or os.path.getmtime(stamp) < os.path.getmtime(os.path.join(web, "package-lock.json")):
        subprocess.run([npm, "ci"], cwd=web, check=True)
    if subprocess.run([npm, "run", "-s", "gen:check"], cwd=web).returncode:   # the firmware tables changed
        if subprocess.run([npm, "run", "gen"], cwd=web).returncode:
            sys.exit("webui: npm run gen failed (PlatformIO, a host C++ compiler and PyYAML are needed)")
    if subprocess.run([npm, "run", "build:app"], cwd=web).returncode:
        sys.exit("webui: npm run build:app failed")
    n = write_header(os.path.join(web, "dist", "app.html"), os.path.join(root, "webui_html.h"))
    print("webui: webui_html.h written (%d B gzip)" % n)


def regmap_needs_build(root, empty):
    """True when regmap_gz.h is missing, older than an input, or the wrong variant (empty vs full)."""
    sys.path.insert(0, os.path.join(os.path.dirname(root), "tools"))
    import regmap   # only its file list here; PyYAML is needed by the subprocess that builds
    header = os.path.join(root, "regmap_gz.h")
    if not os.path.exists(header):
        return True
    with open(header) as f:
        is_empty = "regmap_gz_len = 0;" in f.read()
    return is_empty != empty or (not empty and regmap.stale(header, regmap.inputs(os.path.dirname(root))))


def build_regmap(root):
    """regmap_gz.h (GET /api/regmap) from the ADV Manager maps and tv5725.h; GBSC_NO_REGMAP=1 builds it empty."""
    empty = os.environ.get("GBSC_NO_REGMAP") == "1"
    if not regmap_needs_build(root, empty):
        print("regmap: up to date")
        return
    python = python_cmd()
    if not python:
        sys.exit("regmap: Python is needed (python3, or PYTHON=<interpreter>)")
    tool = os.path.join(os.path.dirname(root), "tools", "regmap.py")
    args = [python, tool, "--header", os.path.join(root, "regmap_gz.h")]
    if empty:
        args.append("--empty")
    elif subprocess.run([python, "-c", "import yaml"], capture_output=True).returncode:
        sys.exit("regmap: PyYAML is needed (pip install pyyaml)")
    if subprocess.run(args).returncode:
        sys.exit("regmap: tools/regmap.py failed")


try:
    Import("env")   # noqa: F821 (SCons)
    build_regmap(env["PROJECT_DIR"])   # noqa: F821
    build(env["PROJECT_DIR"])   # noqa: F821
except NameError:
    if __name__ == "__main__":
        build_regmap(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        build(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
